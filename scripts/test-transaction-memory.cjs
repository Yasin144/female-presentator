const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
let checks = 0;
const equal = (a, b, message) => { assert.deepEqual(a, b, message); checks++; };
(async () => {
  const p = await import(pathToFileURL(path.resolve(__dirname, '../src/components/OtSalary/transactionPresentation.js')));
  const tx = id => ({ id, merchant: 'Person ' + id, type: 'debit', amount: 100 });
  let list = [tx('a'), tx('b'), tx('c')];
  let snapshot = p.reconcileTransactionReadingOrder(null, list, 'all');
  equal(snapshot.ids, ['a', 'b', 'c']);
  let incoming = [tx('new'), ...list];
  equal(p.reconcileTransactionReadingOrder(snapshot, incoming, 'all'), snapshot, 'New arrivals cannot reorder the reading snapshot');
  equal(p.transactionReadingView(snapshot, incoming).rows.map(row => row.id), ['a', 'b', 'c']);
  equal(p.transactionReadingView(snapshot, incoming).pendingCount, 1);
  for (let count = 1; count <= 100; count++) {
    const captures = Array.from({ length: count }, (_, i) => tx('new-' + i)).concat(list);
    const next = p.reconcileTransactionReadingOrder(snapshot, captures, 'all');
    equal(next, snapshot, 'Repeated incoming batches keep visible order');
    equal(p.transactionReadingView(next, captures).pendingCount, count);
  }
  const changed = [{ ...list[0], personalNote: 'Lunch with Ravi', amount: 150 }, list[1], list[2]];
  equal(p.transactionReadingView(snapshot, changed).rows[0].personalNote, 'Lunch with Ravi', 'Authoritative updates remain visible');
  equal(p.transactionReadingView(snapshot, changed).rows[0].amount, 150);
  equal(p.reconcileTransactionReadingOrder(snapshot, [list[2], list[1], list[0]], 'all'), snapshot, 'Timestamp reorder cannot move rows');
  equal(p.reconcileTransactionReadingOrder(snapshot, [list[0], list[2]], 'all').ids, ['a', 'c'], 'Deleted/filtered records are removed');
  equal(p.reconcileTransactionReadingOrder(snapshot, [list[2]], 'search').ids, ['c'], 'Intentional filter change refreshes reading order');
  equal(p.reconcileTransactionReadingOrder({ filterKey: 'all', ids: [] }, list, 'all').ids, ['a', 'b', 'c'], 'First captured records appear on an empty page');
  equal(p.reconcileTransactionReadingOrder(null, [...list, list[0]], 'all').ids, ['a', 'b', 'c']);
  equal(p.transactionIsIncoming({ type: 'refund' }), true);
  equal(p.transactionIsIncoming({ type: 'credit' }), true);
  equal(p.transactionIsIncoming({ type: 'debit' }), false);
  equal(p.transactionPerson({ merchant: '' }), 'Unknown recipient');
  equal(p.transactionPerson({ type: 'credit' }), 'Unknown sender');
  equal(p.transactionMemory({ personalNote: ' Rent ', note: 'old note' }), 'Rent');
  equal(p.transactionMemory({ note: ' Grocery ' }), 'Grocery');
  equal(p.transactionMemory({ paymentRemark: 'BANK/UPI/TXN' }), '', 'A bank remark is not invented personal memory');
  equal(p.recordedBalance({ runningBalance: null, accountBalance: null }), null);
  equal(p.recordedBalance({ runningBalance: '', accountBalance: ' ' }), null);
  equal(p.recordedBalance({ runningBalance: true }), null);
  equal(p.recordedBalance({ runningBalance: 0 }), 0);
  equal(p.recordedBalance({ accountBalance: '123.45' }), 123.45);
  equal(p.recordedBalance({ runningBalance: 'bad', accountBalance: -50 }), -50);
  const original = { id: 'one', merchant: 'Asha Stores', amount: 68, type: 'debit', refId: 'REFERENCE', accountBalance: 1000,
    personalNote: '', note: '', paymentRemark: 'BANK/UPI/REFERENCE', originalRemark: 'Original captured bank text', reconciliationStatus: 'needs_review' };
  const saved = p.saveTransactionMemoryRecord(original, 'Asha Stores', ' Groceries for home ', 1_800_000_000_000);
  equal(saved.personalNote, 'Groceries for home');
  equal(saved.note, 'Groceries for home');
  for (const key of ['id', 'amount', 'type', 'refId', 'accountBalance', 'paymentRemark', 'originalRemark', 'reconciliationStatus']) equal(saved[key], original[key], `Memory editing must preserve ${key}`);
  equal(original.personalNote, '', 'Original record remains immutable');
  equal(p.saveTransactionMemoryRecord(saved, 'Asha Stores', '   ').note, '', 'A memory note can be cleared');
  const before = structuredClone(list);
  p.reconcileTransactionReadingOrder(snapshot, list, 'all'); p.transactionReadingView(snapshot, list);
  equal(list, before, 'Reading state never edits financial records');
  const large = Array.from({ length: 5000 }, (_, i) => tx(String(i)));
  snapshot = p.reconcileTransactionReadingOrder(null, large, 'all');
  equal(p.transactionReadingView(snapshot, [tx('new'), ...large]).rows.length, 5000);
  equal(p.transactionReadingView(snapshot, [tx('new'), ...large]).pendingCount, 1);
  console.log(`PASS: ${checks} transaction reading-order, live-capture, memory, unknown-data and balance scenarios.`);
})().catch(error => { console.error(error); process.exitCode = 1; });
